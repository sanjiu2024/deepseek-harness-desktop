/**
 * Clean build output and test scratch directories.
 *
 * Two kinds of leftovers, for two different reasons:
 *
 *   target/          build cache. `debug` is 18 GB of object files nobody runs: this project
 *                    only ships `release`.
 *   .smoke-home/…    directories the test scripts create. They are per-run by design, so a
 *                    stale one is never useful and can even hide a bug (a smoke test that
 *                    reads yesterday's session list still passes).
 *
 *   node scripts/clean.mjs           # report what would go
 *   node scripts/clean.mjs --apply   # remove it
 *
 * `dist/` and `dist-bundle/` are deliverables, not scratch: they are left alone unless
 * `--all` is passed.
 */
import { existsSync, rmSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { duBytes, human } from './lib/size.mjs'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const apply = process.argv.includes('--apply')
const all = process.argv.includes('--all')

/** Build caches. Regenerated by the next build; safe unless a build is running. */
const buildTargets = [
  ['target/debug', join(root, 'target', 'debug')],
  ['target/release/deps', join(root, 'target', 'release', 'deps')],
  ['target/release/incremental', join(root, 'target', 'release', 'incremental')],
  ['target/release/build', join(root, 'target', 'release', 'build')],
]

/** Scratch directories the test scripts create, one per script. */
const scratchTargets = [
  ['.smoke-home', join(root, '.smoke-home')],
  ['.slim-home', join(root, '.slim-home')],
  ['.capture-home', join(root, '.capture-home')],
  ['.probe-home', join(root, '.probe-home')],
  ['.t-home', join(root, '.t-home')],
  ['.kernel-staging', join(root, '.kernel-staging')],
  ['logs in .dev-home', join(root, '.dev-home', 'logs')],
]

/** Deliverables: only with --all, and the message says so. */
const deliverableTargets = [
  ['dist-bundle', join(root, 'dist-bundle')],
  ['apps/desktop/dist', join(root, 'apps', 'desktop', 'dist')],
]

const groups = [
  ['build cache', buildTargets],
  ['test scratch', scratchTargets],
  ...(all ? [['deliverables', deliverableTargets]] : []),
]

let total = 0
const pending = []

for (const [label, targets] of groups) {
  console.log(`\n[clean] ${label}`)
  for (const [name, path] of targets) {
    if (!existsSync(path)) continue
    const size = duBytes(path)
    total += size
    pending.push(path)
    console.log(`  ${human(size).padStart(8)}  ${name}`)
  }
}

if (pending.length === 0) {
  console.log('\n[clean] nothing to remove')
  process.exit(0)
}

console.log(`\n[clean] ${human(total)} reclaimable`)

if (!apply) {
  console.log('[clean] dry run. Re-run with --apply to remove.')
  if (!all) console.log('[clean] add --all to also drop dist/ and dist-bundle/')
  process.exit(0)
}

let failed = 0
for (const path of pending) {
  try {
    rmSync(path, { recursive: true, force: true })
  } catch (error) {
    // A file another process holds (an editor, a virus scanner, a running shell) is normal on
    // Windows; report it and keep going instead of leaving the rest uncleaned.
    failed += 1
    console.warn(`[clean] could not remove ${path}: ${error.message}`)
  }
}

const leftovers = pending.filter((path) => existsSync(path))
if (leftovers.length > 0) {
  console.warn(`\n[clean] ${leftovers.length} path(s) still present (${failed} error(s)):`)
  for (const path of leftovers) {
    // The tool that names the holder earns its keep here: "access denied" never says who.
    console.warn(`  node scripts/handles.mjs "${path}"`)
  }
} else {
  console.log('[clean] done')
}

// Keep `target/` itself: cargo expects the directory to exist and recreating it is one more
// thing that can fail on a machine where the parent is watched.
const release = join(root, 'target', 'release')
if (existsSync(join(root, 'target')) && !existsSync(release)) {
  console.log('[clean] note: target/release was removed; the next build starts cold')
}

